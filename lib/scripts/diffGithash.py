import argparse
import json
from deepdiff import DeepDiff

parser = argparse.ArgumentParser(
    description="Script to compare git commit hashes between two .json files generated by the Githash modifier.",
    usage= "python lib/scripts/diffGithash.py [DEVELOP_JSON_FILE_PATH] [PR_JSON_FILE_PATH]"
)

parser.add_argument("develop_json_file_path", type=str)
parser.add_argument("pr_json_file_path", type=str)

args = parser.parse_args()

with open(args.develop_json_file_path) as f:
    develop = json.load(f)
    develop = develop.get("packages")
    
with open(args.pr_json_file_path) as f:
    pr = json.load(f)
    pr = pr.get("packages")

diff = DeepDiff(develop, pr, verbose_level=1)

if diff:
    print(diff)
else:
    print("No githash differences found")