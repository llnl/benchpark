import json
import sys
import json
from pathlib import Path

import spack.config as config


def find_dir(root, target_name):
    root = Path(root)
    for path in root.rglob("*"):
        if path.is_dir() and path.name == target_name:
            return path.resolve()
    return None


def main(benchpark_wkp_dir, commit_info_file=None):
    base_dir = Path(__file__).resolve().parents[0]

    cfg_path = find_dir(benchpark_wkp_dir, "auxiliary_software_files")
    ds = config.DirectoryConfigScope("auxpath", cfg_path)
    cfg = config.create_from(ds)
    pkgs_cfg = cfg.get("packages")

    # Load commit requirements if provided
    requirements = {}
    if commit_info_file:
        commit_info_path = base_dir / commit_info_file
        if commit_info_path.exists():
            with open(commit_info_path, "r") as f:
                requirements = json.load(f)

    # Add require constraints for branch-based git packages
    for pkg_name, require_spec in requirements.items():
        pkg_cfg = pkgs_cfg.setdefault(pkg_name, {})
        # Append to existing require list if it exists, otherwise create new list
        if "require" in pkg_cfg:
            # Assume it's already a list (as generated by system.py)
            if isinstance(pkg_cfg["require"], list):
                pkg_cfg["require"].append(require_spec)
            else:
                # If it's not a list, convert it to one
                pkg_cfg["require"] = [pkg_cfg["require"], require_spec]
        else:
            # No existing require, create as list
            pkg_cfg["require"] = [require_spec]

    cfg.set("packages", pkgs_cfg, "auxpath")


if __name__ == "__main__":
    commit_info = sys.argv[2] if len(sys.argv) > 2 else None
    main(sys.argv[1], commit_info)
