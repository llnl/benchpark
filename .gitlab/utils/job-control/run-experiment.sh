#!/bin/bash
set -e

TEST_STATUS_FILE="${CI_PROJECT_DIR}/test_status.txt"

# Activate Virtual Environment
. /usr/workspace/benchpark-dev/benchpark-venv/$SYS_TYPE/bin/activate

echo "./bin/benchpark system init --dest=${HOST} ${ARCHCONFIG} $([ "$HOST" != "matrix" ] && echo "cluster=$HOST") $SYSTEM_ARGS"
echo "./bin/benchpark experiment init --dest=${BENCHMARK} ${HOST} ${BENCHMARK} ${VARIANT}"
echo "./bin/benchpark setup ${HOST}/${BENCHMARK} wkp/"
echo ". wkp/setup.sh"
echo "cd ./wkp/${HOST}/${BENCHMARK}/workspace/"
echo "ramble --disable-logger --workspace-dir . workspace setup"
echo "ramble --disable-logger --workspace-dir . on --executor '{execute_experiment}' --where '{n_nodes} == 1'"
echo "ramble --disable-logger --workspace-dir . workspace analyze --format json yaml text"

printf 'Build\n' > "${TEST_STATUS_FILE}"

# Ensure proper bootstrap location configured
./bin/benchpark configure --bootstrap-location $CUSTOM_CI_BUILDS_DIR

# Initialize System
./bin/benchpark system init --dest=${HOST} ${ARCHCONFIG} $([ "$HOST" != "matrix" ] && echo "cluster=$HOST") $SYSTEM_ARGS

# Daily pipelines on dane and matrix run inside a shared flux allocation (a flux
# instance started in a Slurm job, reached through "flux proxy"), so generate
# flux launch commands. srun from inside that flux job has no Slurm job context
# and would submit a separate Slurm job outside the allocation. Nightly
# pipelines run inside a Slurm allocation, where srun is correct.
if [[ "$HOST" == "dane" || "$HOST" == "matrix" ]] && [[ "$CI_PIPELINE_SOURCE" != "schedule" ]]; then
    sed -i 's/^\(\s*scheduler:\s*\)slurm/\1flux/' "${HOST}/variables.yaml"
    grep -q '^\s*scheduler:\s*flux' "${HOST}/variables.yaml" \
        || { echo "Failed to set 'scheduler: flux' in ${HOST}/variables.yaml"; exit 1; }
fi

# Initialize Experiment
BV=""
if [[ -n "$BENCHMARK_VERSION" ]]; then
    BV="version=$BENCHMARK_VERSION"
fi
./bin/benchpark experiment init --dest=${BENCHMARK} ${HOST} ${BENCHMARK} ${VARIANT} ${BV}

# Build Workspace
./bin/benchpark setup ${HOST}/${BENCHMARK} wkp/

# Setup Ramble & Spack
. wkp/setup.sh

# Setup Workspace
cd ./wkp/${HOST}/${BENCHMARK}/workspace/

ramble --disable-logger --workspace-dir . workspace setup

# Matrix can give CUDA tasks an invalid device mask when using fewer than four
# ranks. Set the mask inside the launched task, after Slurm sets its environment.
# Match both mpi_command and single_rank_mpi_command generated by allocation.
# Only srun lines match, so this applies to nightly runs; daily runs use flux.
if [[ "$HOST" == "matrix" && "$VARIANT" =~ \+cuda($|[[:space:]+~]) ]]; then
    find experiments/ -type f -name execute_experiment -exec sed -E -i \
        '/ env CUDA_VISIBLE_DEVICES=0 /! s/^([[:blank:]]*srun -n [1-3] (--gpus [1-9][0-9]* -N 1|-N 1 --gpus [1-9][0-9]*) )/\1env CUDA_VISIBLE_DEVICES=0 /' {} +
fi

# Runs experiments where n_nodes == 1, and Print Log
printf 'Run\n' > "${TEST_STATUS_FILE}"
# Bound the run and always print experiment logs, even if it hangs (124 = timed out)
run_rc=0
timeout -k 60 60m ramble --disable-logger --workspace-dir . on --executor '{execute_experiment}' --where '{n_nodes} == 1' || run_rc=$?
find experiments/ -type f -name "*.out" -exec cat {} +
if [[ ${run_rc} -ne 0 ]]; then echo "ramble on exited with ${run_rc}"; exit ${run_rc}; fi
# Fail if log files are empty or don't exist
find experiments/ -type f -name "*.out" | grep -q . || { echo "No .out files found"; exit 1; }; find experiments/ -type f -name "*.out" -empty -print -quit | grep -q . && { echo "Empty .out file found"; exit 1; }

if [[ " ${VARIANT} " == *" compiler_attribution=on "* ]]; then
    find experiments/ -type f -name "*.compiler_attribution.trace.jsonl" -size +0c -print -quit \
        | grep -q . || { echo "No nonempty compiler-attribution trace found"; exit 1; }
    find software/ -type f -path "*/compiler-attribution/extraction_plugin_output/*" \
        -name "*.device.json" -size +0c -print -quit \
        | grep -q . || { echo "No nonempty compiler-attribution device extraction found"; exit 1; }
fi

# Analyze Experiments
ramble --disable-logger --workspace-dir . workspace analyze --format json yaml text

cd -

# Test 'benchpark analyze' 
if [[ "$TEST_ANALYZE" == "true" ]]; then
    ./bin/benchpark analyze --workspace-dir ./wkp/${HOST}/${BENCHMARK}/workspace/
fi

# Check Experiment Exit Codes
python ./.gitlab/bin/exit-codes ./wkp/${HOST}/${BENCHMARK}/workspace/results.latest.json

printf 'Pass\n' > "${TEST_STATUS_FILE}"
